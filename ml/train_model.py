#!/usr/bin/env python3
"""Train and evaluate the missed-dose risk model on the SYNTHETIC dataset.

Writes ml/models/adherence_risk.joblib and ml/metrics.json. Every number in metrics.json is
computed here; nothing is hand-entered.
"""
import hashlib
import json
import warnings
from pathlib import Path

import joblib
import numpy as np
from sklearn.compose import ColumnTransformer
from sklearn.dummy import DummyClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.inspection import permutation_importance
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score, precision_score, recall_score, roc_auc_score
from sklearn.model_selection import GroupKFold, GroupShuffleSplit, cross_val_score
from sklearn.pipeline import Pipeline, make_pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

from features import CATEGORICAL, FEATURE_LABELS, FEATURES, NUMERIC, build_training_table, load_dataset

ML_DIR = Path(__file__).resolve().parent
MODEL_PATH = ML_DIR / "models" / "adherence_risk.joblib"
METRICS_PATH = ML_DIR / "metrics.json"
THRESHOLDS = {"moderate": 0.3, "high": 0.6}
SEED = 42
# Harmless: this scikit-learn pins an scipy.optimize option that newer SciPy ignores.
warnings.filterwarnings("ignore", message="Unknown solver options: iprint")
DISCLAIMER = ("Trained and evaluated on synthetic (simulated) data only. "
              "These metrics do not demonstrate real-world or clinical validity.")
TARGET = ("Probability that the patient's next scheduled dose is missed "
          "(not taken within 120 minutes of the scheduled time).")


def build_pipeline(model, scale):
    numeric = [SimpleImputer(strategy="median")] + ([StandardScaler()] if scale else [])
    prep = ColumnTransformer([("num", make_pipeline(*numeric), NUMERIC),
                              ("cat", OneHotEncoder(handle_unknown="ignore"), CATEGORICAL)])
    return Pipeline([("prep", prep), ("model", model)])


def candidates():
    return {
        "baseline_prior": build_pipeline(DummyClassifier(strategy="prior"), scale=False),
        "logistic_regression": build_pipeline(LogisticRegression(max_iter=1000), scale=True),
        "random_forest": build_pipeline(RandomForestClassifier(
            n_estimators=200, max_depth=8, min_samples_leaf=50, random_state=SEED, n_jobs=-1), scale=False),
    }


def split_by_patient(table):
    """Train/test split where each patient's doses land entirely on one side."""
    train, test = next(GroupShuffleSplit(n_splits=1, test_size=0.2, random_state=SEED)
                       .split(table, table["missed"], groups=table["patient_id"]))
    assert not set(table.iloc[train]["patient_id"]) & set(table.iloc[test]["patient_id"]), "patient leak"
    return train, test


def table_hash(table):
    return hashlib.sha256(table.to_csv(index=False).encode("utf-8")).hexdigest()[:8]


def r4(x):
    return None if x is None else round(float(x), 4)


def evaluate(pipe, X, y):
    proba = pipe.predict_proba(X)[:, 1]
    pred = (proba >= 0.5).astype(int)
    try:
        auc = roc_auc_score(y, proba)
    except ValueError:  # only one class in y
        auc = None
    return {"accuracy": r4(accuracy_score(y, pred)),
            "precision": r4(precision_score(y, pred, zero_division=0)),
            "recall": r4(recall_score(y, pred, zero_division=0)),
            "f1": r4(f1_score(y, pred, zero_division=0)),
            "roc_auc": r4(auc),
            "confusion_matrix": confusion_matrix(y, pred, labels=[0, 1]).tolist()}


def distribution(y):
    return {"missed": int((y == 1).sum()), "taken": int((y == 0).sum())}


def reliability_notes(m):
    tr, te = m["class_distribution"]["train"], m["class_distribution"]["test"]
    sel = m["test_metrics"][m["selected_model"]]
    cv = m["cross_validation"]
    gap = abs(cv["logistic_regression"]["roc_auc_mean"] - cv["random_forest"]["roc_auc_mean"])
    spread = max(cv[k]["roc_auc_std"] for k in ("logistic_regression", "random_forest"))
    notes = [
        "The data are synthetic and generated by hand-written rules, so the model partly rediscovers "
        "those rules; scores here say little about how it would behave on real patients.",
        f"Test examples from the same patient are correlated (about {m['data']['examples'] // (m['data']['train_patients'] + m['data']['test_patients'])} "
        f"examples per patient, only {m['data']['test_patients']} test patients), so examples are not independent "
        "and the test metrics are less certain than the example count suggests. There are no confidence intervals.",
        f"Missed doses are the minority class: {tr['missed'] / (tr['missed'] + tr['taken']):.1%} of training "
        f"and {te['missed'] / (te['missed'] + te['taken']):.1%} of test examples. Always predicting 'taken' "
        f"would already score {te['taken'] / (te['taken'] + te['missed']):.1%} accuracy on the test set, so accuracy alone is misleading.",
        f"At the 0.5 probability threshold the selected model finds {sel['recall']:.1%} of missed doses "
        f"(recall) with {sel['precision']:.1%} precision"
        + (", which is low recall for the minority class; the 0.3 and 0.6 risk bands are prototype values "
           "and were not tuned against these results." if sel["recall"] < 0.5 else
           "; the 0.3 and 0.6 risk bands are prototype values and were not tuned against these results."),
        "Probabilities were not calibrated and no calibration check was done, so a displayed probability "
        "should not be read as a literal frequency.",
        "Training uses knowledge time = the target dose's scheduled time. In the app the knowledge time can be "
        "earlier than the next dose (for example the 14:00 cohort snapshot), so the most recent doses may "
        "still be unresolved there; in the training data the previous dose is always resolved by the time "
        "the next one is due, so the model has not seen that situation.",
        "The saved model is fitted on the training patients only (80% of patients); the held-out patients "
        "were not used to fit it, so the test numbers come from a single split (random_state=42).",
    ]
    if gap < spread:
        notes.append(f"The cross-validation gap between the two candidates ({gap:.4f}) is smaller than the "
                     f"fold-to-fold spread ({spread:.4f}), so the choice of model is not strongly supported.")
    return notes


def main():
    data = load_dataset()
    table = build_training_table(data)
    train_idx, test_idx = split_by_patient(table)
    train, test = table.iloc[train_idx], table.iloc[test_idx]
    X_train, y_train, groups = train[FEATURES], train["missed"], train["patient_id"]
    X_test, y_test = test[FEATURES], test["missed"]

    models = candidates()
    cv, cv_mean = {}, {}
    for name, pipe in models.items():
        scores = cross_val_score(pipe, X_train, y_train, groups=groups, cv=GroupKFold(n_splits=5), scoring="roc_auc")
        cv_mean[name] = scores.mean()
        cv[name] = {"roc_auc_mean": r4(scores.mean()), "roc_auc_std": r4(scores.std())}
    # Held-out CV decides; a tie goes to the simpler model. The baseline is reference only.
    selected = "random_forest" if cv_mean["random_forest"] > cv_mean["logistic_regression"] else "logistic_regression"
    other = "logistic_regression" if selected == "random_forest" else "random_forest"

    for pipe in models.values():
        pipe.fit(X_train, y_train)
    test_metrics = {name: evaluate(pipe, X_test, y_test) for name, pipe in models.items()}

    chosen = models[selected]
    imp = permutation_importance(chosen, X_test, y_test, scoring="roc_auc", n_repeats=5, random_state=SEED)
    importance = sorted(({"feature": f, "label": FEATURE_LABELS[f], "importance_mean": r4(m), "importance_std": r4(s)}
                         for f, m, s in zip(FEATURES, imp.importances_mean, imp.importances_std)),
                        key=lambda d: -d["importance_mean"])

    typical = {f: float(np.nanmedian(X_train[f])) for f in NUMERIC}
    typical.update({f: str(X_train[f].mode().iloc[0]) for f in CATEGORICAL})
    version = f"{selected}-{table_hash(table)}"

    metrics = {
        "disclaimer": DISCLAIMER,
        "model_version": version,
        "selected_model": selected,
        "selection_reason": ("Higher mean ROC-AUC in 5-fold patient-grouped cross-validation on training "
                             f"patients ({cv[selected]['roc_auc_mean']:.3f} vs {cv[other]['roc_auc_mean']:.3f})."),
        "target": TARGET,
        "data": {"examples": len(table), "train_patients": int(groups.nunique()),
                 "test_patients": int(test["patient_id"].nunique()),
                 "train_examples": len(train), "test_examples": len(test)},
        "class_distribution": {"train": distribution(y_train), "test": distribution(y_test)},
        "cross_validation": cv,
        "test_metrics": test_metrics,
        "feature_importance": importance,
        "risk_thresholds": {**THRESHOLDS, "note": "Prototype thresholds, not medically validated."},
    }
    metrics["reliability_notes"] = reliability_notes(metrics)

    MODEL_PATH.parent.mkdir(exist_ok=True)
    joblib.dump({"pipeline": chosen, "features": FEATURES, "typical_values": typical, "model_version": version,
                 "thresholds": THRESHOLDS, "grace_minutes": data.meta["grace_minutes"]}, MODEL_PATH, compress=3)
    METRICS_PATH.write_text(json.dumps(metrics, indent=2, sort_keys=True) + "\n")
    summarize(metrics)


def summarize(m):
    d, cd = m["data"], m["class_distribution"]
    print(f"examples: {d['examples']} (train {d['train_examples']} / {d['train_patients']} patients, "
          f"test {d['test_examples']} / {d['test_patients']} patients)")
    print(f"class balance train: {cd['train']}  test: {cd['test']}")
    print("CV ROC-AUC (5-fold, grouped by patient): " + "; ".join(
        f"{k}={v['roc_auc_mean']:.4f}±{v['roc_auc_std']:.4f}" for k, v in m["cross_validation"].items()))
    print(f"selected: {m['selected_model']}  ({m['selection_reason']})")
    for name, t in m["test_metrics"].items():
        print(f"test {name}: acc={t['accuracy']} prec={t['precision']} rec={t['recall']} f1={t['f1']} "
              f"auc={t['roc_auc']} cm={t['confusion_matrix']}")
    print("top importances: " + "; ".join(
        f"{i['feature']}={i['importance_mean']:.4f}±{i['importance_std']:.4f}" for i in m["feature_importance"][:5]))
    print(f"model_version: {m['model_version']}")
    print(f"model file: {MODEL_PATH} ({MODEL_PATH.stat().st_size / 1e3:.1f} KB)")


if __name__ == "__main__":
    main()
